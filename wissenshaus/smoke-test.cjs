const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname,'..');
const read = p => fs.readFileSync(path.join(root,p),'utf8');
const js = read('wissenshaus/app.js');
const html = read('wissenshaus/index.html');
const css = read('wissenshaus/style.css');
const manifest = JSON.parse(read('wissenshaus/dua-manifest.json'));
const index = JSON.parse(read('content/posts/posts-index.json'));
const books = JSON.parse(read('data/books-library.json'));
const quran = JSON.parse(read('content/quran/001.json'));
const daily = JSON.parse(read('content/updates/daily.json'));
const tad = JSON.parse(read('apple-tv/quran/tadabbur/entries-index.json'));
assert.match(html,/id="main"/);assert.match(html,/id="overlay"/);
assert.match(html,/app\.js/);assert.match(html,/style\.css/);
assert.match(css,/@media\(max-width:850px\)/);
assert.match(js,/function showPost/);assert.match(js,/function showDua/);
assert.match(js,/function showBook/);assert.match(js,/function showVerse/);
assert.match(js,/function moreTad/);assert.match(js,/function saveFavorite/);
assert.match(js,/data\/books-library\.json/);
assert.equal(index.files.length,index.count);
assert.equal(manifest.paths.length,97);
assert(manifest.paths.every(p=>fs.existsSync(path.join(root,p))));
assert.equal(quran.verses.length,7);
assert(books.books.some(b=>b.verification==='verified'));
assert(tad.files.length>0);assert(daily.recommendation&&daily.dua);
const expected = ['posts','library','quran','dua','tadabbur','ai','saved','more'];
assert(expected.every(name=>js.includes("'"+name+"'")));
console.log('Wissenshaus static/data smoke checks passed: posts='+index.count+', duas='+manifest.paths.length+', tadabbur files='+tad.files.length);
