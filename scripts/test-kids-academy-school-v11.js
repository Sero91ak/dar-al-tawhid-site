#!/usr/bin/env node
"use strict";
const fs=require("node:fs");
const vm=require("node:vm");
const assert=require("node:assert/strict");
const path=require("node:path");
const ROOT=path.resolve(__dirname,"..");
const read=(p)=>fs.readFileSync(path.join(ROOT,p),"utf8");
const sandbox=vm.createContext({window:{}});
for(const src of ["kids/akademie/curriculum-v1.js","kids/akademie/curriculum-v2.js","kids/akademie/school-progress-v11.js"])
 new vm.Script(read(src),{filename:src}).runInContext(sandbox,{timeout:1500});
const curriculum=sandbox.window.DARKidsAcademyCurriculum;
const school=sandbox.window.DARKidsAcademySchool;
assert.equal(school.version,"v11-20261010");
const topics={akhlaq:["sidq","akhlaq-sabr","akhlaq-amanah"],adab:["adab-salam","adab-worte","adab-respekt"],fiqh:["fiqh-taharah","fiqh-wudu","fiqh-salah"],aqidah:["aqidah-tawhid","aqidah-iman","aqidah-ikhlas"]};
for(const [lessonId,lesson] of Object.entries(curriculum))
 if(!topics[lesson.subject].includes(lessonId))topics[lesson.subject].push(lessonId);
const ids=Array.from(school.sequence(topics));
assert.equal(ids.length,34);
assert.equal(new Set(ids).size,34);
assert.deepEqual(ids.slice(0,4),["sidq","adab-salam","fiqh-taharah","aqidah-tawhid"]);
const day=(day,month=9)=>new Date(2026,month,day,12,0,0);
const run=(date,records={},drafts={})=>school.evaluate({topics,records,drafts,now:date});
const sunday=run(day(11));
assert.equal(sunday.mode,"free");
assert.equal(sunday.active,ids[0],"First lesson is immediately open even on Sunday");
assert.equal(sunday.access(ids[0]),"new");
assert.equal(sunday.access(ids[1]),"locked");
assert.equal(sunday.access(ids[2]),"locked");
assert.equal(sunday.completed,0);
const firstDone={id:"kid-A",age:"4-5",lessonId:ids[0],firstCompletedAt:day(11).getTime(),completedAt:day(11).getTime(),nextDue:day(12).getTime()};
const progressA={[ids[0]]:firstDone};
const completedSunday=run(day(11),progressA);
assert.equal(completedSunday.active,null,"No second class in one day");
assert.equal(completedSunday.access(ids[0]),"review");
assert.equal(completedSunday.access(ids[1]),"locked");
assert.equal(completedSunday.recommendation,ids[0],"After completing class, only review remains");
const monday=run(day(12),progressA);
assert.equal(monday.mode,"new");
assert.equal(monday.active,ids[1]);
assert.equal(monday.access(ids[1]),"new");
assert.equal(monday.access(ids[2]),"locked");
const secondDone={lessonId:ids[1],firstCompletedAt:day(12).getTime(),completedAt:day(12).getTime(),nextDue:day(13).getTime()};
const progressB={...progressA,[ids[1]]:secondDone};
assert.equal(run(day(12),progressB).access(ids[2]),"locked","Second newly completed lesson cannot unlock third on same Monday");
const tuesday=run(day(13),progressB);
assert.equal(tuesday.active,ids[2],"Tuesday unlocks the next lesson");
const thirdDone={lessonId:ids[2],firstCompletedAt:day(13).getTime(),completedAt:day(13).getTime()};
const progressC={...progressB,[ids[2]]:thirdDone};
assert.equal(run(day(14),progressC).mode,"review");
assert.equal(run(day(14),progressC).access(ids[3]),"locked","Wednesday reviews, no new lesson");
assert.equal(run(day(15),progressC).access(ids[3]),"new","Thursday starts next new unit");
const repeated={...firstDone,completedAt:day(15).getTime()};
assert.equal(run(day(15),{...progressB,[ids[0]]:repeated}).access(ids[2]),"new",
 "Reviewing the first topic must not reset graduation to a future date");
const oldDrafts={[ids[4]]:{savedAt:day(11).getTime(),step:2,qIndex:1}};
const resume=run(day(15),progressA,oldDrafts);
assert.equal(resume.active,ids[4],"Previously started lesson stays resumable");
assert.equal(resume.access(ids[4]),"resume");
assert.equal(resume.access(ids[5]),"locked");
assert.equal(run(day(1,11),progressA,oldDrafts).access(ids[4]),"resume","Stored incomplete lesson must not expire in seven days");
assert.equal(run(day(12)).access(ids[1]),"locked","Different child cannot inherit an earlier child's unlocks");
const full=Object.fromEntries(ids.map(lessonId=>[lessonId,{lessonId,completedAt:day(11).getTime(),nextDue:day(12).getTime()}]));
const graduate=run(day(13),full);
assert.equal(graduate.active,null);
assert.equal(graduate.upcoming,null);
assert.equal(graduate.access(ids[33]),"review");
const html=read("kids/akademie/index.html");
assert.ok(html.includes('school-progress-v11.js?v=20261010-11'));
assert.ok(html.includes('data-preview-release="V12.0-voicepilot-20261010"')||html.includes('data-preview-release="V11.0-20261010"'),"Supported sequential school release marker");
assert.ok(html.includes('academySchoolState().access(chosen)'));
assert.ok(html.includes('card.disabled=locked'));
assert.ok(html.includes('firstCompletedAt:Number(prev?.firstCompletedAt||prev?.completedAt||Date.now())'));
assert.ok(!html.includes("elapsed>7*86400000"),"Unfinished lessons never expire");
const inline=html.slice(html.lastIndexOf("<script>")+8,html.lastIndexOf("</script>"));
new vm.Script(inline);
console.log("KIDS SCHOOL V11 PASSED: 34 lessons, one active at a time, next-day gate, Wed/Sat review, indefinite resume, locked deep links.");
