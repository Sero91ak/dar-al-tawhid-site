    static func prepare(_ input: String) -> String {
        var output = input
        for rule in rules {
            guard rule.source != rule.spoken, output.contains(rule.source) else { continue }
            output = replaceBounded(in: output, source: rule.source, spoken: rule.spoken)
        }
        return output
    }

    private static func replaceBounded(in text: String, source: String, spoken: String) -> String {
        guard !source.isEmpty else { return text }
        let escaped = NSRegularExpression.escapedPattern(for: source)
        let startsWithWord = source.unicodeScalars.first.map { CharacterSet.alphanumerics.contains($0) } ?? false
        let endsWithWord = source.unicodeScalars.last.map { CharacterSet.alphanumerics.contains($0) } ?? false
        let prefix = startsWithWord ? "(?<![\\p{L}\\p{N}])" : ""
        let suffix = endsWithWord ? "(?![\\p{L}\\p{N}])" : ""
        guard let regex = try? NSRegularExpression(pattern: prefix + escaped + suffix) else { return text }
        let range = NSRange(text.startIndex..<text.endIndex, in: text)
        return regex.stringByReplacingMatches(
            in: text,
            options: [],
            range: range,
            withTemplate: NSRegularExpression.escapedTemplate(for: spoken)
        )
    }
