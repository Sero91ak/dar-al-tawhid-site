#!/usr/bin/env node
"use strict";
const fs=require("node:fs"),path=require("node:path"),assert=require("node:assert/strict");
const root=path.resolve(__dirname,"../.."),read=p=>fs.readFileSync(path.join(root,p),"utf8");
const flow=read(".github/workflows/build-kids-academy-v9-staging.yml");
const code=read("kids/tools/build-academy-v9-staging.py");
const request=JSON.parse(read("kids/data/academy-sidq-v18-request.json"));
const sidq=JSON.parse(read("kids/data/academy-sidq-voice-plan-v18.json"));
const policy=JSON.parse(read("kids/data/academy-voice-policy-v10.json"));
assert.ok(flow.includes("workflow_dispatch:"),"Never generate clips from a push");
assert.ok(!/^  push:/m.test(flow),"MUST NOT bill on automatic push");
assert.ok(flow.includes("inputs.confirm == 'GENERATE-FOUR'"),"Explicit credit confirmation required");
assert.equal(policy.costControls.maxClipsPerInvocation,4);
assert.equal(policy.costControls.autoPublishWithoutOwnerReview,false);
assert.equal(request.voiceId,policy.voiceIdentity.voiceId);
assert.equal(request.modelId,"eleven_v4");
assert.equal(request.voiceSettingsProfile,"kids_story");
assert.equal(request.maxClips,4);
assert.equal(request.maxPreparedCharacters,350);
assert.equal(new Set(request.exactPhrases).size,4);
assert.ok(request.exactPhrases.every(t=>sidq.phrases.some(p=>p.text===t)),"All four phrases must be tied to genuine lesson steps");
assert.ok(flow.includes("--dry-run --sidq-v18 --limit 4 --max-chars 350"));
assert.ok(flow.includes("--sidq-v18 --limit 4 --max-chars 350"));
assert.ok(flow.includes('set(data["entries"])==set(request["exactPhrases"])'));
assert.ok(flow.includes('p=pathlib.Path("kids/data/academy-audio-staging-sidq-v18.json")'));
assert.ok(flow.includes("git add kids/data/academy-audio-staging-sidq-v18.json kids/assets/kids-academy-audio/"));
assert.ok(!flow.includes("git add kids/data/academy-audio-staging-v9.json"),"Original four staged clips must remain immutable");
assert.ok(!flow.includes("kids/data/academy-audio.json"),"Never commit directly to public voice catalog");
assert.ok(code.includes("if not args.dry_run and not args.sidq_v18 and not args.pilot_first_lesson:"));
assert.ok(code.includes("if args.sidq_v18:"));
console.log("KIDS V21 VOICE BUDGET SAFE: first additional 4 phrases only, manual trigger, V4 kids_story, no public release, original 4 preserved.");
