#!/usr/bin/env node
"use strict";
const fs=require("node:fs"),vm=require("node:vm"),path=require("node:path"),assert=require("node:assert/strict");
const root=path.resolve(__dirname,"../../.."),read=p=>fs.readFileSync(path.join(root,p),"utf8");
const page=read("test/kids/akademie/lehrplan.html");
const creator=read("test/kids/akademie/index.html");
const plan=JSON.parse(read("kids/data/academy-expansion-roadmap-v23.json"));
const gate=read("cloudflare/preview-gate.js");
assert.ok(page.includes('<meta name="robots" content="noindex,nofollow,noarchive">'));
assert.ok(creator.includes('href="/test/kids/akademie/lehrplan.html"'));
assert.ok(creator.includes('href="/test/kids/akademie/audio-audit.html"'),"Do not regress to the broken old audio link");
assert.ok(gate.includes('pathname.startsWith("/test/kids/")'),"The editor view must remain protected");
assert.ok(!page.includes("localStorage")&&!page.includes("indexedDB"),"No real child account or progress reads");
assert.ok(!page.includes("speechSynthesis")&&!page.includes("ELEVENLABS_API_KEY"),"No unreviewed speech or credits");
assert.ok(page.includes('credentials:"same-origin"'),"Do not bypass the Kids gate");
assert.ok(page.includes('releaseGate?.childAppUnlocked!==false'));
assert.ok(page.includes('releaseGate?.reviewerApproved!==false'));
assert.ok(page.includes('name="robots"'));
assert.ok(page.includes('textContent=String(text||"")'),"Never directly write unverified prose as HTML");
assert.ok(!page.includes(".innerHTML"),"Do not render editorial input as HTML");
assert.ok(page.includes('const state={plan:null,units:[],filtered:[],selected:null,age:"4-5"}'));
assert.ok(page.includes('data-age="6-8"')&&page.includes('data-age="9-10"'));
assert.ok(page.includes('id="prev"')&&page.includes('id="next"'),"One topic at a time instead of long multi-page scrolling");
assert.equal(plan.plannedUnits.length,170);assert.equal(plan.strandSummary.length,12);
assert.equal(plan.curriculum.alreadyImplementedLessons,38);
assert.equal(plan.curriculum.totalNewLessonSlots,208);
assert.ok(plan.plannedUnits.every(u=>u.releaseGate?.childAppUnlocked===false),"Editorial drafts must stay locked");
const inline=[...page.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].pop();
assert.ok(inline);new vm.Script(inline[1],{filename:"kids-roadmap-v23-preview-inline.js"});
console.log("KIDS ROADMAP PREVIEW PASS: 38 live + 170 fully gated editorial topics, 12 pillars, 3 age methods, protected read-only viewer.");
